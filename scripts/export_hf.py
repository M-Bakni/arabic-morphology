# site/verbs.json writes the bare quadriliteral pattern without vowels.
SITE_PATTERN = {"فَعْلَلَ": "فعلل"}

STR = pa.string()
VERB_SCHEMA = pa.schema(
    [
        ("verb", STR),
        ("root", STR),
        ("root_type", STR),
        ("augmentation", STR),
        ("form", STR),
        ("pattern", STR),
        ("transitivity", STR),
        ("transitivity_code", STR),
        ("verb_type", STR),
    ]
)


def fail(message: str) -> None:
    sys.exit(f"export_hf: {message}")


def read_table(table: Table) -> tuple[list[str], list[dict[str, str | None]]]:
    """The CSV as a list of rows, with cells stripped and empty cells as None."""
    with table.csv_path.open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        header = list(reader.fieldnames or [])
        rows = [
            {k: (v.strip() or None) for k, v in row.items()} for row in reader
        ]

    patterns = [h for h in header if h != ROOT_COLUMN and not h.startswith(LETTER_PREFIX)]
    letters = [h for h in header if h.startswith(LETTER_PREFIX)]
    if patterns != list(table.forms):
        fail(f"{table.csv_path.name}: unexpected pattern columns {patterns}")
    for row in rows:
        root = row[ROOT_COLUMN]
        if "".join(row[c] or "" for c in letters) != root:
            fail(f"{table.csv_path.name}: root {root} does not match its letters")
        for p in patterns:
            if row[p] is not None and row[p] not in TRANSITIVITY:
                fail(f"{table.csv_path.name}: {root} / {p} has the value {row[p]!r}")

    with table.json_path.open(encoding="utf-8") as f:
        as_json = [{k: v.strip() if v else None for k, v in r.items()} for r in json.load(f)]
    if as_json != rows:
        fail(f"data/json/{table.json_path.name} differs from data/csv/{table.csv_path.name}")
    return header, rows


def load_site_verbs() -> dict[tuple[str, str, str, str], tuple[str, str, str]]:
    """(root, cat, deriv, pattern) -> (vocalized verb, transitivity letter, verb type)."""
    data = json.loads(SITE_VERBS.read_text(encoding="utf-8"))
    idx = {name: i for i, name in enumerate(data["fields"])}
    letter = {"l": "ل", "m": "م", "k": "ك"}
    out = {}
    for r in data["rows"]:
        key = (r[idx["root"]], r[idx["cat"]], r[idx["deriv"]], r[idx["pattern"]])
        if key in out:
            fail(f"site/verbs.json has {key} twice")
        out[key] = (r[idx["verb"]], letter[r[idx["trans"]]], r[idx["type"]] or None)
    return out


def write_parquet(columns: dict[str, list], schema: pa.Schema, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    table = pa.table({name: pa.array(columns[name], type=STR) for name in schema.names}, schema=schema)
    pq.write_table(table, path, compression="zstd")


def export() -> dict[str, int]:
    shutil.rmtree(OUT_DIR, ignore_errors=True)
    site = load_site_verbs()
    verbs: list[dict[str, str | None]] = []
    counts: dict[str, int] = {}

    for table in TABLES:
        header, rows = read_table(table)
        schema = pa.schema([(h, STR) for h in header])
        write_parquet(
            {h: [r[h] for r in rows] for h in header},
            schema,
            OUT_DIR / "data" / f"{table.config}.parquet",
        )
        counts[f"{table.config}_roots"] = len(rows)

        n_verbs = 0
        for row in rows:
            root = row[ROOT_COLUMN]
            for pattern, form in table.forms.items():
                code = row[pattern]
                if code is None:
                    continue
                key = (root, *table.site_key, SITE_PATTERN.get(pattern, pattern))
                if key not in site:
                    fail(f"site/verbs.json has no verb for {key}")
                verb, site_code, verb_type = site.pop(key)
                if site_code != code:
                    fail(f"{key}: the table says {code}, site/verbs.json says {site_code}")
                verbs.append(
                    {
                        "verb": verb,
                        "root": root,
                        "root_type": table.root_type,
                        "augmentation": table.augmentation,
                        "form": form,
                        "pattern": pattern,
                        "transitivity": TRANSITIVITY[code],
                        "transitivity_code": code,
                        "verb_type": verb_type,
                    }
                )
                n_verbs += 1
        counts[f"{table.config}_verbs"] = n_verbs

    if site:
        fail(f"site/verbs.json has {len(site)} verbs missing from the tables, e.g. {next(iter(site))}")

    # Group every root's verbs together: bare before augmented, then table order.
    order = {t.config: i for i, t in enumerate(TABLES)}
    position = {(t.root_type, t.augmentation): order[t.config] for t in TABLES}
    verbs.sort(key=lambda v: (v["root"], position[(v["root_type"], v["augmentation"])]))
    write_parquet(
        {name: [v[name] for v in verbs] for name in VERB_SCHEMA.names},
        VERB_SCHEMA,
        OUT_DIR / "data" / "verbs.parquet",
    )
    counts["verbs"] = len(verbs)
    for code, label in TRANSITIVITY.items():
        counts[label] = sum(1 for v in verbs if v["transitivity_code"] == code)

    (OUT_DIR / "README.md").write_text(render_card(counts), encoding="utf-8")
    print(f"Wrote {len(verbs)} verbs and the four tables to {OUT_DIR}")
    return counts


def commit_sha() -> str:
    sha = os.environ.get("GITHUB_SHA")
    if sha:
        return sha
    try:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return ""


def render_card(counts: dict[str, int]) -> str:
    sha = commit_sha()
    if sha:
        source = f"[`{sha[:7]}`](https://github.com/{GITHUB_REPO}/commit/{sha})"
    else:
        source = "an uncommitted working copy"
    template = Template(CARD_TEMPLATE.read_text(encoding="utf-8"))
    return template.substitute(
        **counts,
        exported_from=source,
        exported_on=date.today().isoformat(),
    )


def push(repo: str, message: str) -> None:
    token = os.environ.get("HF_TOKEN")
    if not token:
        fail("HF_TOKEN is not set: it needs a token with write access to the dataset")
    from huggingface_hub import HfApi

    api = HfApi(token=token)
    # The token is scoped to this one dataset and cannot create repos, so the
    # dataset is created by hand on the Hub before the first push.
    if not api.repo_exists(repo, repo_type="dataset"):
        fail(f"https://huggingface.co/datasets/{repo} does not exist: create it on the Hub first")
    api.upload_folder(
        repo_id=repo,
        repo_type="dataset",
        folder_path=OUT_DIR,
        path_in_repo=".",
        allow_patterns=["README.md", "data/*.parquet"],
        # Drop Parquet files that this export no longer writes.
        delete_patterns=["data/*.parquet"],
        commit_message=message,
    )
    print(f"Pushed to https://huggingface.co/datasets/{repo}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--push", action="store_true", help="upload hf/ to the Hub")
    parser.add_argument("--repo", default=DEFAULT_REPO, help="Hub dataset repo id")
    parser.add_argument("--message", default="Update from GitHub", help="Hub commit message")
    args = parser.parse_args()
    export()
    if args.push:
        push(args.repo, args.message)


if __name__ == "__main__":
    main()
